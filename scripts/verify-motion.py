"""Exercise the motion landing page and preserved business portfolio routes."""
import json
import os
from pathlib import Path
from playwright.sync_api import sync_playwright

BASE = os.environ.get('PORTFOLIO_URL', 'http://127.0.0.1:4173')
OUT = Path('docs/verification')
checks, errors = [], []

def check(name, condition):
    assert condition, name
    checks.append(name)
    print('PASS: ' + name, flush=True)

def settle(page):
    page.wait_for_function('document.fonts.status === "loaded"')
    page.wait_for_timeout(200)

def scroll(page, selector, offset=100):
    page.locator(selector).first.evaluate('(el, offset) => window.scrollTo({top: el.getBoundingClientRect().top + scrollY - offset, behavior:"instant"})', offset)
    page.wait_for_timeout(650)

with sync_playwright() as p:
    browser = p.chromium.launch()
    context = browser.new_context(viewport={'width': 1440, 'height': 1000}, permissions=['clipboard-read', 'clipboard-write'])
    page = context.new_page()
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(BASE)
    settle(page)
    page.wait_for_timeout(1700)
    check('Hero uses two complete title lines', page.locator('.m-title-line').count() == 2)
    check('All five project stories are present', page.locator('.ix-project-detail').count() == 5)
    check('Hero ribbon loaded', page.locator('.m-ribbon-depth img').evaluate('el => el.complete && el.naturalWidth > 0'))
    check('Hero shows the real Mai photograph', page.locator('.m-portrait-photo img').get_attribute('src') == '/assets/mai-portrait.webp' and page.locator('.m-portrait-photo img').evaluate('el => el.complete && el.naturalWidth > 0'))
    before_float = page.locator('.m-portrait-float').evaluate('el => getComputedStyle(el).transform')
    page.wait_for_timeout(550)
    check('Portrait moves without pointer input', before_float != page.locator('.m-portrait-float').evaluate('el => getComputedStyle(el).transform'))
    check('Ambient elements run in view', page.locator('.m-hero').get_attribute('data-ambient') == 'on')
    check('Outfit display font loaded', page.evaluate('document.fonts.check("800 100px Outfit")'))
    page.locator('.m-hero').hover(position={'x': 120, 'y': 200})
    page.wait_for_timeout(500)
    check('Ribbon responds to pointer', page.locator('.m-ribbon-pointer').evaluate('el => !!el.style.transform && el.style.transform !== "translate(0px, 0px)"'))
    page.get_by_role('button', name='Explore my work', exact=True).click()
    page.wait_for_timeout(1200)
    check('Hero action scrolls to real work', page.locator('#selected-work').bounding_box()['y'] < 200)
    check('Ambient hero pauses outside viewport', page.locator('.m-hero').get_attribute('data-ambient') == 'off')
    scroll(page, '.ix-exhibit', 100)
    check('Only the selected project is exposed', page.locator('.ix-project-detail:not([inert])').count() == 1)
    check('Council annual and event metrics remain distinct', 'annual council budget' in page.locator('.ix-project-detail.is-active').inner_text() and 'S3/2025 participants' in page.locator('.ix-project-detail.is-active').inner_text())
    for label, project in [('Michelin', 'michelin'), ('Career Checkpoint', 'checkpoint'), ('Careers Fair', 'careers-fair'), ('CTM', 'ctm')]:
        page.get_by_role('button', name=label, exact=True).click()
        check(project + ' selection updates photograph and detail link', page.locator('.ix-exhibit').get_attribute('data-project') == project and page.locator('.ix-project-detail.is-active a').get_attribute('href') == '#/work/' + project)
    page.locator('.ix-project-detail.is-active').wait_for(state='visible')
    check('CTM claim is contribution share', 'contribution share' in page.locator('.ix-project-detail.is-active').inner_text())
    page.get_by_role('button', name='Next project', exact=True).click()
    check('Project next wraps to first', page.locator('.ix-exhibit').get_attribute('data-project') == 'council')
    page.locator('.ix-work-visual').focus()
    page.keyboard.press('ArrowLeft')
    check('Project keyboard wraps backwards', page.locator('.ix-exhibit').get_attribute('data-project') == 'ctm')
    box = page.locator('.ix-work-visual').bounding_box()
    x, y = box['x'] + box['width'] * .6, box['y'] + 180
    page.mouse.move(x, y)
    page.mouse.down()
    page.mouse.move(x - 150, y + 3, steps=12)
    check('Project follows the drag before release', page.locator('.ix-work-visual').get_attribute('data-dragging') == 'true' and page.locator('.ix-work-visual').evaluate('el => parseFloat(el.style.getPropertyValue("--drag"))') < -50)
    page.mouse.up()
    check('Project mouse drag changes story', page.locator('.ix-exhibit').get_attribute('data-project') == 'council')
    scroll(page, '.ix-photo-stage')
    page.wait_for_timeout(700)
    before_life = page.locator('.ix-photo-life').first.evaluate('el => getComputedStyle(el).transform')
    page.wait_for_timeout(500)
    check('Photo deck floats while in view', before_life != page.locator('.ix-photo-life').first.evaluate('el => getComputedStyle(el).transform'))
    page.get_by_role('button', name='Next moment', exact=True).click()
    check('Photo deck next changes story', page.locator('.ix-moment-tabs [aria-pressed=true]').inner_text() == 'People')
    page.locator('.ix-photo-stage').focus()
    page.keyboard.press('ArrowLeft')
    check('Photo deck supports keyboard', page.locator('.ix-moment-tabs [aria-pressed=true]').inner_text() == 'Meet Mai')
    page.get_by_role('button', name='Previous moment', exact=True).click()
    check('Photo deck wraps backwards', page.locator('.ix-moment-tabs [aria-pressed=true]').inner_text() == 'Day 1')
    page.get_by_role('button', name='Meet Mai', exact=True).click()
    page.wait_for_timeout(600)
    page.get_by_role('button', name='Show People', exact=True).click()
    check('Clicking a neighboring photo selects it', page.locator('.ix-moment-tabs [aria-pressed=true]').inner_text() == 'People')
    page.wait_for_timeout(600)
    box = page.locator('.ix-photo-stage').bounding_box()
    x, y = box['x'] + box['width'] * .5, box['y'] + 200
    page.mouse.move(x, y)
    page.mouse.down()
    page.mouse.move(x - 160, y + 4, steps=14)
    check('Photo deck follows the pointer', page.locator('.ix-photo-stage').get_attribute('data-dragging') == 'true')
    page.mouse.up()
    check('Photo deck mouse drag changes story', page.locator('.ix-moment-tabs [aria-pressed=true]').inner_text() == 'Leadership')
    scroll(page, '.m-contact')
    page.get_by_role('button', name='Copy email', exact=True).click()
    page.get_by_role('button', name='Email copied').wait_for()
    check('Email copy gives confirmation', page.get_by_role('button', name='Email copied').is_visible())
    check('Clipboard contains the real email', page.evaluate('navigator.clipboard.readText()') == 'ngocmaimia056@gmail.com')
    page.locator('.m-footer-sign a').click()
    page.wait_for_timeout(1200)
    check('Footer returns to top', page.evaluate('scrollY') < 5)
    page.get_by_role('button', name='Pause motion').click()
    check('Motion toggle disables animations', page.locator('html').get_attribute('data-motion') == 'off')
    check('Pause stops portrait ambient controller', page.locator('.m-hero').get_attribute('data-ambient') == 'off')
    frozen_pose = page.locator('.m-portrait-float').evaluate('el => getComputedStyle(el).transform')
    page.wait_for_timeout(400)
    check('Portrait remains still while paused', frozen_pose == page.locator('.m-portrait-float').evaluate('el => getComputedStyle(el).transform'))
    check('Pause removes all GSAP pins', page.locator('.pin-spacer').count() == 0)
    check('Pause stops marquee', page.locator('.m-marquee-track').evaluate('el => { const s = getComputedStyle(el); return s.animationPlayState === "paused" || s.animationName === "none"; }'))
    check('Paused introduction remains readable', page.locator('.ix-about-heading').evaluate('el => getComputedStyle(el).opacity') == '1')
    page.get_by_role('button', name='People', exact=True).click()
    check('Paused photo deck remains interactive', page.locator('.ix-moment-tabs [aria-pressed=true]').inner_text() == 'People')
    page.get_by_role('button', name='Enable motion').click()
    scroll(page, '.ix-photo-stage')
    check('Resume restores photo deck ambient motion', page.locator('.ix-photo-stage').get_attribute('data-ambient') == 'on')
    page.goto(BASE + '/#/work/michelin')
    settle(page)
    check('Leaving homepage cleans up GSAP pins', page.locator('.pin-spacer').count() == 0)
    page.get_by_role('button', name='Enlarge project cover').click()
    check('Project evidence dialog opens', page.locator('dialog').evaluate('el => el.open'))
    page.keyboard.press('Escape')
    check('Escape closes evidence', not page.locator('dialog').evaluate('el => el.open'))
    page.locator('[role=tab]').nth(1).click()
    page.keyboard.press('ArrowRight')
    check('Project decision tabs retain keyboard behavior', page.locator('[role=tab][aria-selected=true]').get_attribute('id') == 'process-step-2')
    for width in [1440, 1024, 768, 390, 375, 320]:
        page.set_viewport_size({'width': width, 'height': 900 if width > 800 else 844})
        for route in ['', 'work', 'journey', 'notes', 'hello', 'work/michelin', 'work/checkpoint', 'work/council', 'work/careers-fair', 'work/ctm']:
            page.goto(BASE + '/#/' + route)
            settle(page)
            check(f'{width}px {route or "home"}: no horizontal overflow', page.evaluate('document.documentElement.scrollWidth <= innerWidth + 1'))
            if route == '':
                check(f'{width}px title fits inside viewport', page.locator('.m-title-line').last.evaluate('el => el.scrollWidth <= el.clientWidth + 1'))
                check(f'{width}px Mai photo appears in opening viewport', page.locator('.m-portrait-photo').evaluate('el => {const r=el.getBoundingClientRect();return r.top >= 0 && r.bottom < innerHeight && r.width > 170;}'))
                if width == 390:
                    page.wait_for_timeout(1500)
                    page.get_by_role('button', name='Open navigation').click()
                    check('Mobile menu opens', page.locator('.chapter-nav').is_visible())
                    page.get_by_role('navigation', name='Main navigation').get_by_role('link', name='About Mai').click()
                    page.wait_for_url('**/#/notes')
                    page.locator('.chapter-nav').wait_for(state='hidden')
                    check('Mobile menu changes route and closes', page.url.endswith('#/notes') and not page.locator('.chapter-nav').is_visible())
                    page.goto(BASE)
                    settle(page)
                    scroll(page, '.ix-photo-stage', 100)
                    box = page.locator('.ix-photo-stage').bounding_box()
                    session = page.context.new_cdp_session(page)
                    x, y = box['x'] + box['width'] * .8, box['y'] + 150
                    session.send('Input.dispatchTouchEvent', {'type': 'touchStart', 'touchPoints': [{'x': x, 'y': y}]})
                    session.send('Input.dispatchTouchEvent', {'type': 'touchMove', 'touchPoints': [{'x': x - 120, 'y': y + 2}]})
                    session.send('Input.dispatchTouchEvent', {'type': 'touchEnd', 'touchPoints': []})
                    page.wait_for_timeout(300)
                    check('Mobile swipe changes photo deck', page.locator('.ix-moment-tabs [aria-pressed=true]').inner_text() == 'People')
                    session.send('Input.dispatchTouchEvent', {'type': 'touchStart', 'touchPoints': [{'x': x, 'y': y}]})
                    session.send('Input.dispatchTouchEvent', {'type': 'touchMove', 'touchPoints': [{'x': x - 100, 'y': y + 2}]})
                    session.send('Input.dispatchTouchEvent', {'type': 'touchCancel', 'touchPoints': []})
                    check('Cancelled touch leaves story unchanged', page.locator('.ix-moment-tabs [aria-pressed=true]').inner_text() == 'People')
                    check('Cancelled touch clears drag state', page.locator('.ix-photo-stage').get_attribute('data-dragging') == 'false')

            if width == 1440 and route in ['work', 'notes', 'work/michelin']:
                page.screenshot(path=str(OUT / ('motion-inner-' + route.replace('/', '-') + '.png')))
    page.goto(BASE + '/#/hello')
    page.get_by_role('button', name='Turn the postcard').click()
    check('Contact postcard still flips', 'flipped' in page.locator('.postcard-scene').get_attribute('class'))
    reduced = browser.new_page(viewport={'width': 1440, 'height': 900}, reduced_motion='reduce')
    reduced.goto(BASE)
    settle(reduced)
    check('System reduced motion is respected', reduced.locator('html').get_attribute('data-motion') == 'off')
    check('Reduced motion has no pins', reduced.locator('.pin-spacer').count() == 0)
    check('Reduced motion shows introduction', reduced.locator('.ix-about-heading').evaluate('el => getComputedStyle(el).opacity') == '1')
    check('Reduced motion disables marquee animation', reduced.locator('.m-marquee-track').evaluate('el => getComputedStyle(el).animationName') == 'none')
    check('Reduced motion disables decorative orbit', reduced.locator('.m-portrait-orbit').evaluate('el => getComputedStyle(el).animationName') == 'none')
    reduced.get_by_role('button', name='Next moment', exact=True).click()
    check('Reduced motion keeps photo deck usable', reduced.locator('.ix-moment-tabs [aria-pressed=true]').inner_text() == 'People')
    cv = page.request.get(BASE + '/ngoc-mai-cv.pdf')
    check('CV returns a valid PDF', cv.status == 200 and 'application/pdf' in cv.headers.get('content-type', ''))
    check('No uncaught browser errors', not errors)
    browser.close()

OUT.joinpath('motion-browser-results.json').write_text(json.dumps({'passed': len(checks), 'checks': checks, 'errors': errors, 'base': BASE}, indent=2), encoding='utf-8')
print(f'{len(checks)} checks passed.')
