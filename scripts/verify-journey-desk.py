"""Production browser acceptance for the restored Three.js journey desk."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE = 'http://127.0.0.1:4173'
OUT = Path('docs/verification')
checks, errors = [], []

def check(name, result):
    assert result, name
    checks.append(name)
    print('PASS: ' + name, flush=True)

def ready(page):
    page.locator('.j-desk-canvas[data-scene-state=ready]').wait_for(timeout=60000)
    page.wait_for_function("Number(document.querySelector('.j-desk-canvas').dataset.frames)>0")

def stage_in_view(page):
    page.locator('.j-desk-wrap').evaluate('(el)=>window.scrollTo({top:el.getBoundingClientRect().top+scrollY-85,behavior:"instant"})')
    page.wait_for_timeout(400)

with sync_playwright() as p:
    browser = p.chromium.launch()
    context = browser.new_context(viewport={'width':1440,'height':1000}, device_scale_factor=1)
    page = context.new_page()
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto(BASE+'/#/journey')
    ready(page)
    stage = page.locator('.j-desk-canvas')
    page.wait_for_timeout(1200)
    check('Journey shows real WebGL canvas', page.locator('.j-desk-canvas canvas').evaluate('el=>!!el.getContext("webgl2")'))
    check('Canvas matches display pixel ratio', page.locator('.j-desk-canvas canvas').evaluate('el=>el.width>=el.clientWidth*devicePixelRatio-1'))
    check('Five accessible chapter controls', page.locator('.j-chapters button').count()==5)
    check('Intro reflects youthful growth', 'Still growing.' in page.locator('h1').inner_text())
    page.screenshot(path=str(OUT/'journey-desk-desktop.png'))
    stage_in_view(page)
    box=page.locator('.j-desk-canvas canvas').bounding_box()
    page.mouse.click(box['x']+box['width']*.32,box['y']+box['height']*.55)
    expect(page.locator('.j-company')).to_have_text('Student Council')
    check('Clicking the actual notebook mesh selects Council', page.url.endswith('/journey/0'))
    page.wait_for_timeout(700)
    page.mouse.move(10,300)
    page.screenshot(path=str(OUT/'journey-desk-council.png'))
    for i, name in enumerate(['Council notebook','CTM phone','Careers photo','Michelin folder','TikTok laptop']):
        page.get_by_role('button',name='Explore '+name,exact=True).click()
        expect(page.locator('.j-chapters button').nth(i)).to_have_attribute('aria-pressed','true')
        check(f'{name} opens correct chapter and URL',page.url.endswith('/journey/'+str(i)))
    check('TikTok role remains the actual internship',page.locator('.j-role').inner_text()=='AI Data Service & Operations Intern')
    page.locator('.j-chapters button').last.focus()
    page.keyboard.press('ArrowRight')
    expect(page.locator('.j-company')).to_have_text('Student Council')
    check('Keyboard wraps from final to first chapter',page.locator('.j-chapters button').first.evaluate('el=>el===document.activeElement'))
    page.keyboard.press('End')
    expect(page.locator('.j-company')).to_have_text('TikTok')
    check('End key selects newest chapter',page.url.endswith('/journey/4'))
    page.get_by_text('A little more of the story',exact=False).click()
    check('Full reflection remains available on demand',page.locator('.j-reflection').get_attribute('open') is not None and 'ByteDance' in page.locator('.j-reflection').inner_text())
    stage_in_view(page)
    page.get_by_role('button',name='Whole desk',exact=True).click()
    expect(page.locator('.j-overview')).to_be_visible()
    check('Whole desk returns to overview without scrolling to top',page.url.endswith('/journey') and page.evaluate('scrollY')>100)
    before=stage.get_attribute('data-view-angle')
    box=page.locator('.j-desk-canvas canvas').bounding_box()
    x,y=box['x']+box['width']*.5,box['y']+box['height']*.85
    page.mouse.move(x,y);page.mouse.down();page.mouse.move(x+130,y+2,steps=12);page.mouse.up();page.wait_for_timeout(700)
    check('Dragging rotates the real desk',abs(float(stage.get_attribute('data-view-angle'))-float(before))>.15)
    check('Drag does not accidentally select a chapter',page.locator('.j-overview').count()==1)
    page.get_by_role('button',name='Whole desk',exact=True).click();page.wait_for_timeout(700)
    page.wait_for_function("Math.abs(Number(document.querySelector('.j-desk-canvas').dataset.viewAngle))<.01",timeout=15000)
    check('Whole desk restores camera angle',abs(float(stage.get_attribute('data-view-angle')))<.01)
    page.get_by_role('button',name='Rotate desk left',exact=True).click();page.wait_for_timeout(600)
    page.wait_for_function("Number(document.querySelector('.j-desk-canvas').dataset.viewAngle)<-.1",timeout=15000)
    check('Keyboard-accessible view controls rotate desk',float(stage.get_attribute('data-view-angle'))<-.1)
    page.get_by_role('button',name='Pause motion',exact=True).click()
    stage_in_view(page);page.wait_for_timeout(350)
    count=stage.get_attribute('data-frames');page.wait_for_timeout(500)
    check('Paused desk stops rendering frames',count==stage.get_attribute('data-frames'))
    page.get_by_role('button',name='Explore Michelin folder',exact=True).click()
    expect(page.locator('.j-company')).to_have_text('Michelin')
    check('Paused scene selection remains functional',page.url.endswith('/journey/3'))
    page.get_by_role('button',name='Enable motion',exact=True).click();stage_in_view(page)
    count=stage.get_attribute('data-frames');page.wait_for_timeout(400)
    check('Resume restarts visible scene rendering',int(stage.get_attribute('data-frames'))>int(count))
    page.goto(BASE+'/#/journey/2');ready(page)
    expect(page.locator('.j-company')).to_have_text('RMIT Careers')
    check('Direct chapter URL opens the right story',page.locator('.j-chapters button').nth(2).get_attribute('aria-pressed')=='true')
    page.get_by_role('button',name='Explore TikTok laptop',exact=True).click()
    page.go_back();expect(page.locator('.j-company')).to_have_text('RMIT Careers')
    check('Browser back synchronizes chapter selection',page.locator('.j-chapters button').nth(2).get_attribute('aria-pressed')=='true')
    for width in [1440,1024,768,390,375,320]:
        page.set_viewport_size({'width':width,'height':900 if width>800 else 844})
        ready(page);page.wait_for_timeout(250)
        check(f'{width}px Journey has no horizontal overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
        check(f'{width}px chapter controls meet 44px height',page.locator('.j-chapters button').evaluate_all('els=>els.every(el=>el.getBoundingClientRect().height>=44)'))
    page.set_viewport_size({'width':390,'height':844})
    page.goto(BASE+'/#/journey');ready(page);page.wait_for_timeout(400)
    page.screenshot(path=str(OUT/'journey-desk-mobile.png'),full_page=True)
    stage_in_view(page)
    box=page.locator('.j-desk-canvas canvas').bounding_box();x,y=box['x']+box['width']*.55,box['y']+box['height']*.65
    session=context.new_cdp_session(page)
    for event,points in [('touchStart',[{'x':x,'y':y}]),('touchMove',[{'x':x-100,'y':y+2}]),('touchEnd',[])]:
        session.send('Input.dispatchTouchEvent',{'type':event,'touchPoints':points})
    page.wait_for_timeout(500)
    check('Touch horizontal drag rotates the desk',float(stage.get_attribute('data-view-angle'))<-.15)
    before=page.evaluate('scrollY')
    for event,points in [('touchStart',[{'x':x,'y':y}]),('touchMove',[{'x':x+2,'y':y-150}]),('touchEnd',[])]:
        session.send('Input.dispatchTouchEvent',{'type':event,'touchPoints':points})
    page.wait_for_timeout(500)
    check('Vertical swipe preserves native page scrolling',page.evaluate('scrollY')>before+30)
    page.locator('.j-chapters button').nth(4).click()
    expect(page.locator('.j-company')).to_have_text('TikTok')
    check('Mobile chapter strip selects newest chapter',page.url.endswith('/journey/4'))
    page.set_viewport_size({'width':1440,'height':450})
    page.locator('.j-reflection summary').click()
    page.locator('.j-footer').scroll_into_view_if_needed();page.wait_for_timeout(400)
    count=stage.get_attribute('data-frames');page.wait_for_timeout(400)
    check('Offscreen desk stops rendering',count==stage.get_attribute('data-frames'))
    page.goto(BASE+'/#/');page.wait_for_timeout(300)
    check('Leaving Journey removes the canvas',page.locator('.j-desk-canvas canvas').count()==0)
    check('Homepage retains photograph and interactive stories',page.locator('.m-portrait-photo img').count()==1 and page.locator('.ix-exhibit').count()==1)
    page.goto(BASE+'/#/journey/0');ready(page)
    check('Returning to Journey initializes a fresh scene',page.locator('.j-desk-canvas canvas').count()==1)
    page.locator('.j-desk-canvas canvas').evaluate('el=>el.getContext("webgl2").getExtension("WEBGL_lose_context").loseContext()')
    expect(stage).to_have_attribute('data-scene-state','failed')
    page.locator('.j-chapters button').nth(3).click();expect(page.locator('.j-company')).to_have_text('Michelin')
    check('WebGL context failure preserves chapter access',page.locator('.j-desk-fallback').is_visible())
    reduced=browser.new_page(viewport={'width':1200,'height':900},reduced_motion='reduce')
    reduced.goto(BASE+'/#/journey/4');ready(reduced);reduced.wait_for_timeout(500)
    check('System reduced motion is respected',reduced.locator('html').get_attribute('data-motion')=='off')
    count=reduced.locator('.j-desk-canvas').get_attribute('data-frames');reduced.wait_for_timeout(450)
    check('Reduced-motion rendering rests when unchanged',count==reduced.locator('.j-desk-canvas').get_attribute('data-frames'))
    reduced.locator('.j-chapters button').first.click();expect(reduced.locator('.j-company')).to_have_text('Student Council')
    check('Reduced-motion chapter selection still works',reduced.url.endswith('/journey/0'))
    reduced.set_viewport_size({'width':390,'height':844})
    reduced.get_by_role('button',name='Whole desk',exact=True).click();reduced.wait_for_timeout(150)
    stage_in_view(reduced)
    check('Mobile markers have >=44px hit targets and 22px visual faces',reduced.locator('.j-markers button').evaluate_all('els=>els.length===5&&els.every(el=>{const r=el.getBoundingClientRect(),s=el.querySelector("span").getBoundingClientRect();return getComputedStyle(el).pointerEvents!=="none"&&r.width>=43.99&&r.height>=43.99&&Math.round(s.width)===22&&Math.round(s.height)===22})'))
    reduced_session=reduced.context.new_cdp_session(reduced)
    for i in range(5):
        reduced.get_by_role('button',name='Whole desk',exact=True).click();reduced.wait_for_timeout(100)
        stage_in_view(reduced)
        mb=reduced.locator('.j-markers button').nth(i).bounding_box()
        mx,my=mb['x']+mb['width']/2,mb['y']+mb['height']/2
        for event,points in [('touchStart',[{'x':mx,'y':my}]),('touchEnd',[])]:
            reduced_session.send('Input.dispatchTouchEvent',{'type':event,'touchPoints':points})
        reduced.wait_for_timeout(100)
        check(f'Mobile touch at marker {i+1} center selects chapter {i}',reduced.url.endswith(f'/journey/{i}') and reduced.locator('.j-chapters button').nth(i).get_attribute('aria-pressed')=='true')
    reduced.close()
    fallback=browser.new_page(viewport={'width':390,'height':844})
    fallback.add_init_script("const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){if(type==='webgl2'||type==='webgl'||type==='experimental-webgl')return null;return original.call(this,type,...args)}")
    fallback.goto(BASE+'/#/journey');expect(fallback.locator('.j-desk-canvas')).to_have_attribute('data-scene-state','failed',timeout=15000)
    fallback.locator('.j-chapters button').nth(1).click();expect(fallback.locator('.j-company')).to_have_text('CTM')
    check('Unavailable WebGL has a usable fallback',fallback.locator('.j-desk-fallback').is_visible())
    fallback.close()
    check('No uncaught browser errors',not errors)
    context.close();browser.close()

OUT.joinpath('journey-desk-results.json').write_text(json.dumps({'passed':len(checks),'checks':checks,'errors':errors},indent=2),encoding='utf-8')
print(f'{len(checks)} checks passed.')
